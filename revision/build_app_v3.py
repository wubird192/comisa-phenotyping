def rd(name, **kw):
    p = os.path.join(csv_dir, name)
    if os.path.exists(p):
        return pd.read_csv(p, **kw)
    missing_inputs.append(name); return None

out = []
def H(s): out.append(f"\n{s}\n")
def P(s): out.append(s + "\n\n")
def md_table(df, floatfmt="{:.2f}", index=False):
    df = df.copy()
    if index: df = df.reset_index()
    cols = list(df.columns)
    lines = ["| " + " | ".join(str(c) for c in cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.astype(object).iterrows():
        cells = []
        for c in cols:
            v = r[c]
            if isinstance(v, (float, np.floating)):
                cells.append("" if pd.isna(v) else floatfmt.format(v))
            else:
                cells.append(str(v))
        lines.append("| " + " | ".join(cells) + " |")
    out.append("\n" + "\n".join(lines) + "\n\n")
def neg(s):  # typographic minus
    return s.replace("-", "−")
def fmt_p(v):
    return "< 0.001" if v < 0.001 else f"{v:.3f}"
def fmt_p2(v):
    return "< 0.001" if v < 0.001 else f"{v:.2f}"

